// OASIS Common Alerting Protocol (CAP 1.2) serialisation for advisories.

import type { Advisory, AlertLevel } from "./types";
import { DISTRICTS } from "./data/districts";

const SEVERITY: Record<AlertLevel, string> = { RED: "Extreme", ORANGE: "Severe", YELLOW: "Moderate", GREEN: "Minor" };
const URGENCY: Record<AlertLevel, string> = { RED: "Immediate", ORANGE: "Expected", YELLOW: "Future", GREEN: "Future" };
const RESPONSE: Record<AlertLevel, string> = { RED: "Evacuate", ORANGE: "Prepare", YELLOW: "Monitor", GREEN: "Monitor" };
const LANG_CODE: Record<string, string> = { Bengali: "bn", Bangla: "bn", Odia: "or", Telugu: "te", Tamil: "ta", Burmese: "my", Hindi: "hi" };

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function iso(d: Date): string {
  return d.toISOString().replace(/\.\d{3}Z$/, "+00:00");
}

export function buildCap(
  a: Advisory,
  opts: { stormName: string; exercise: boolean; sentAt?: Date; sender?: string },
): string {
  const sent = opts.sentAt ?? new Date();
  const onset = a.leadTimeHours != null ? new Date(sent.getTime() + a.leadTimeHours * 3600e3) : sent;
  const expires = new Date(Math.max(sent.getTime() + 24 * 3600e3, onset.getTime() + 36 * 3600e3));
  const status = opts.exercise ? "Exercise" : process.env.CAP_ALLOW_ACTUAL === "true" ? "Actual" : "Test";
  const sender = opts.sender ?? process.env.CAP_SENDER ?? "landfall-decision-support@localhost";
  const areas = a.districts
    .map((name) => DISTRICTS.find((d) => d.name === name || name.startsWith(d.name)))
    .filter((d): d is (typeof DISTRICTS)[number] => !!d)
    .map(
      (d) =>
        `      <area>\n        <areaDesc>${esc(`${d.name}, ${d.admin1}`)}</areaDesc>\n        <circle>${d.lat},${d.lon} 45</circle>\n      </area>`,
    )
    .join("\n");
  const instruction = [...a.actions.map((x) => `[${x.timeframe}] ${x.action}`), ...a.infrastructureActions].join("\n");
  const info = (lang: string, headline: string, description: string, instr: string) => `  <info>
    <language>${lang}</language>
    <category>Met</category>
    <event>Tropical Cyclone ${esc(opts.stormName)}</event>
    <responseType>${RESPONSE[a.alertLevel]}</responseType>
    <urgency>${URGENCY[a.alertLevel]}</urgency>
    <severity>${SEVERITY[a.alertLevel]}</severity>
    <certainty>${a.confidence === "high" ? "Likely" : "Possible"}</certainty>
    <effective>${iso(sent)}</effective>
    <onset>${iso(onset)}</onset>
    <expires>${iso(expires)}</expires>
    <senderName>Landfall anticipatory-action decision support (prototype)</senderName>
    <headline>${esc(headline)}</headline>
    <description>${esc(description)}</description>
    <instruction>${esc(instr)}</instruction>
    <parameter><valueName>AlertColour</valueName><value>${a.alertLevel}</value></parameter>
    <parameter><valueName>Authority</valueName><value>${esc(a.authorityName)}</value></parameter>
${areas}
  </info>`;
  const local =
    a.localLanguage?.headline && !a.localLanguage.headline.startsWith("(")
      ? "\n" + info(LANG_CODE[a.localLanguage.language] ?? "und", a.localLanguage.headline, a.localLanguage.smsText, a.localLanguage.smsText)
      : "";
  return `<?xml version="1.0" encoding="UTF-8"?>
<alert xmlns="urn:oasis:names:tc:emergency:cap:1.2">
  <identifier>${esc(`landfall-${opts.stormName}-${a.id}`.replace(/\s+/g, "-"))}</identifier>
  <sender>${esc(sender)}</sender>
  <sent>${iso(sent)}</sent>
  <status>${status}</status>
  <msgType>Alert</msgType>
  <scope>Restricted</scope>
  <restriction>For disaster-management authorities. Official warnings from the national meteorological service take precedence.</restriction>
  <note>Decision-support draft generated by a parametric ensemble model; human-reviewed before release.</note>
${info("en", a.headline, a.summary, instruction)}${local}
</alert>
`;
}
